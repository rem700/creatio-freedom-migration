// --- How to migrate section / detail grid columns (addGridDataColumns, profile) ---
// In Classic UI the VISIBLE columns of a section or detail list are user
// settings stored in the profile ("Select fields to display"), not code. A
// column that code needs but the user may hide is added to the list QUERY by
// overriding addGridDataColumns(esq) (callParent, then esq.addColumn guarded
// by esq.columns.contains). Freedom UI declares columns in the list page's
// schema: "columns" on the crt.DataGrid (code = attribute name) plus one
// attribute per column in the collection's viewModelConfig.attributes
// ("Items" on a list page, path "PDS.<Column>"). A column the code needs but
// does not show is an attribute without a column definition.
//
// API MAP
//   profile / "Select fields to display"     ->  DataTable "columns": [{ id, code, caption, dataValueType }]
//   addGridDataColumns(esq) + esq.addColumn("UsrType")
//                                            ->  Items.viewModelConfig.attributes.PDS_UsrType:
//                                                    { modelConfig: { path: "PDS.UsrType" } }
//   esq.columns.contains("UsrType")          ->  not needed: attributes are keyed, no duplicate error
//   this.get("GridData").find(id).get("UsrType")
//                                            ->  await row.PDS_UsrType (row of await $context.Items)
//   getEditPageName() by record type         ->  no section hook: typified pages / crt.OpenPageRequest
//                                                with modelInitConfigs [{ action: "edit", recordId }]
//   column caption (profile)                 ->  "caption": "#ResourceString(PDS_UsrName)#"
//   detail grid columns                      ->  the same, on the list's own collection attribute
//
// DOES NOT CARRY OVER ONE-TO-ONE
//   - Visible columns move from user data into the schema. The Classic
//     default profile ("save for all users") has to be redone as the columns
//     array; user profiles are not migrated by this.
//   - A column definition alone is not enough: its `code` must be an
//     attribute of the collection, or the cell renders empty.
//   - Lookup cells arrive as { value, displayValue } in both generations.
//   - dataValueType codes come from the devkit DataValueType enum
//     (1 Text, 4 Integer, 6 Money, 7 DateTime, 10 Lookup, 12 Boolean).
//
// SILENT FAILURE WHEN PORTED MECHANICALLY
//   A column that is NOT DISPLAYED and NOT declared as an attribute reads as
//   undefined on every row - no error. Code that routes or enables actions by
//   that column works for the developer who shows it and fails for everyone
//   else, exactly like Classic without addGridDataColumns. Declare the
//   attribute for every column a handler reads.
//
// Applies: Creatio 8.1+; Classic UI 7.x–8.x
// Source: https://academy.creatio.com/guides/dev/development-on-creatio-platform/8.1/front-end-development/freedom-ui/client-schema-freedomui/overview
// Source: https://www.npmjs.com/package/@creatio-devkit/common (typings: DataValueType, ViewModelCollection)
// Source: https://academy.creatio.com/api/jscoreapi/7.15.0/ (Terrasoft.EntitySchemaQuery columns)

// ===== CLASSIC UI (7.x) =====================================================

define("UsrMyEntitySection", [], function() {

	const MyEntityTypeSpecial = "d4e5f6a7-b8c9-4d0e-9f1a-2b3c4d5e6f01";

	return {
		entitySchemaName: "UsrMyEntity",
		methods: {
			// Load UsrType / UsrIsLocked whether or not the user shows them.
			addGridDataColumns: function(esq) {
				this.callParent(arguments);
				["UsrType", "UsrIsLocked"].forEach(function(columnName) {
					if (!esq.columns.contains(columnName)) {
						esq.addColumn(columnName);
					}
				});
			},

			isSpecialRowActive: function() {
				var activeRowId = this.get("ActiveRow");
				var row = activeRowId && this.get("GridData").find(activeRowId);
				var type = row && row.get("UsrType");
				return !!type && type.value === MyEntityTypeSpecial;
			}
		},
		diff: /**SCHEMA_DIFF*/[]/**SCHEMA_DIFF*/
	};
});

