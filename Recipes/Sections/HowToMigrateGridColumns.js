define("UsrMyEntity_ListPage", /**SCHEMA_DEPS*/[]/**SCHEMA_DEPS*/, function/**SCHEMA_ARGS*/()/**SCHEMA_ARGS*/ {

	const MyEntityTypeSpecial = "d4e5f6a7-b8c9-4d0e-9f1a-2b3c4d5e6f01";
	// Column ids are generated by the designer; invented placeholders here.
	const ColumnNameId = "e5f6a7b8-c9d0-4e1f-8a2b-3c4d5e6f7a01";
	const ColumnOwnerId = "e5f6a7b8-c9d0-4e1f-8a2b-3c4d5e6f7a02";

	return {
		viewConfigDiff: /**SCHEMA_VIEW_CONFIG_DIFF*/[
			{
				// The visible columns (was the default profile).
				"operation": "merge",
				"name": "DataTable",
				"values": {
					"primaryColumnName": "PDS_Id",
					"columns": [
						{
							"id": ColumnNameId,
							"code": "PDS_UsrName",
							"caption": "#ResourceString(PDS_UsrName)#",
							"dataValueType": 1
						},
						{
							"id": ColumnOwnerId,
							"code": "PDS_UsrOwner",
							"caption": "#ResourceString(PDS_UsrOwner)#",
							"dataValueType": 10
						}
					]
				}
			}
		]/**SCHEMA_VIEW_CONFIG_DIFF*/,
		viewModelConfigDiff: /**SCHEMA_VIEW_MODEL_CONFIG_DIFF*/[
			{
				// Was addGridDataColumns: loaded for every row, shown or not.
				"operation": "merge",
				"path": ["attributes", "Items", "viewModelConfig", "attributes"],
				"values": {
					"PDS_UsrType": { "modelConfig": { "path": "PDS.UsrType" } },
					"PDS_UsrIsLocked": { "modelConfig": { "path": "PDS.UsrIsLocked" } }
				}
			}
		]/**SCHEMA_VIEW_MODEL_CONFIG_DIFF*/,
		modelConfigDiff: /**SCHEMA_MODEL_CONFIG_DIFF*/[]/**SCHEMA_MODEL_CONFIG_DIFF*/,
		handlers: /**SCHEMA_HANDLERS*/[
			{
				// Row action: "recordId": "$Items.PDS_Id" in rowToolbarItems.
				request: "usr.CheckRowTypeRequest",
				handler: async (request, next) => {
					const rows = await request.$context.Items;
					for (const row of (rows || [])) {
						if (await row.PDS_Id !== request.recordId) {
							continue;
						}
						const type = await row.PDS_UsrType;   // undefined if not declared above
						request.$context.UsrIsSpecialRow = type?.value === MyEntityTypeSpecial;
					}
					return next?.handle(request);
				}
			}
		]/**SCHEMA_HANDLERS*/,
		converters: /**SCHEMA_CONVERTERS*/{}/**SCHEMA_CONVERTERS*/,
		validators: /**SCHEMA_VALIDATORS*/{}/**SCHEMA_VALIDATORS*/
	};
});
